import Combine
import Foundation
import FyoloShared

/// What the file tree marks on a row, beyond its name and icon.
struct FileDecoration: Equatable {
    /// Code nobody reviews line by line, painted behind the row.
    enum Kind: Equatable {
        case test
        case generated
    }

    /// How the file differs from the branch's base, in the name's color.
    enum Change: Equatable {
        /// Not there at the base: written on this branch, committed or not.
        case added
        /// There at the base, and changed since.
        case modified
        /// Changed since the base only in whitespace — indentation, wrapping, blank
        /// lines — so nothing it does is different.
        case cosmetic
    }

    var kind: Kind?
    var change: Change?
    /// Matched by `.gitignore`, as the device reported it with the listing.
    var isIgnored = false
    /// A compiler, type checker or linter printed an error naming this file — or, on a
    /// folder, naming a file somewhere inside it.
    var hasError = false
}

/// Tells test code and generated code apart from hand-written source, by path alone, the
/// way each ecosystem names them. Pure, so the rules are pinned by tests rather than by
/// whatever repository happened to be open when they were written.
///
/// A path's own `.gitattributes` (`linguist-generated`) and a generated file's own header
/// are read separately, by `FileTreeDecorations`, where a disk is there to read them.
enum FileClassifier {
    /// The category of `relativePath` — relative to the tree's root, `/`-separated — or
    /// `nil` for ordinary source. Generated wins over test: a protobuf stub inside a
    /// `tests/` folder is still not something anyone wrote.
    static func kind(of relativePath: String, isDirectory: Bool) -> FileDecoration.Kind? {
        if isDirectory ? isInGeneratedFolder(relativePath) : isGenerated(relativePath) { return .generated }
        let components = relativePath.split(separator: "/").map(String.init)
        guard let name = components.last else { return nil }
        // A folder is judged by its own name and its parents; a file by its parents and
        // then its name.
        let folders = isDirectory ? components : Array(components.dropLast())
        if folders.contains(where: isTestFolder) { return .test }
        if !isDirectory, isTestFile(name) { return .test }
        return nil
    }

    // MARK: Generated

    private static let generatedFolders: Set<String> = [
        "__generated__", "generated", "@generated", "autogenerated", "auto-generated",
    ]

    static func isGeneratedFolder(_ name: String) -> Bool {
        generatedFolders.contains(name.lowercased())
    }

    /// Whether a file, by its path relative to the root, is generated. The question the
    /// whole-tree folder pass asks of every file in a checkout, so it is answered without
    /// splitting the path or running the test rules.
    static func isGenerated(_ relativePath: String) -> Bool {
        guard let slash = relativePath.lastIndex(of: "/") else { return isGeneratedFile(relativePath) }
        return isInGeneratedFolder(String(relativePath[..<slash]))
            || isGeneratedFile(String(relativePath[relativePath.index(after: slash)...]))
    }

    /// Whether any component of `folderPath` is a generated folder. Every such name
    /// contains "generated", which nearly no path does, so that is checked first.
    private static func isInGeneratedFolder(_ folderPath: String) -> Bool {
        guard containsIgnoringCase(folderPath, "generated") else { return false }
        return folderPath.split(separator: "/").contains { isGeneratedFolder(String($0)) }
    }

    /// Whether `text` contains `needle` (lowercase ASCII), ignoring ASCII case. A byte
    /// scan rather than Foundation's `range(of:options:)`, whose bridging dominated a
    /// pass over a quarter-million paths.
    private static func containsIgnoringCase(_ text: String, _ needle: StaticString) -> Bool {
        let pattern = UnsafeBufferPointer(start: needle.utf8Start, count: needle.utf8CodeUnitCount)
        guard let first = pattern.first else { return true }
        let bytes = Array(text.utf8)
        guard bytes.count >= pattern.count else { return false }
        for start in 0...(bytes.count - pattern.count) where bytes[start] | 0x20 == first {
            var index = 1
            while index < pattern.count, bytes[start + index] | 0x20 == pattern[index] { index += 1 }
            if index == pattern.count { return true }
        }
        return false
    }

    /// Lockfiles and other manifests a package manager writes, by exact name.
    private static let generatedNames: Set<String> = [
        // JavaScript
        "package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml", "bun.lockb",
        "bun.lock", "deno.lock", ".pnp.cjs", ".pnp.loader.mjs", "next-env.d.ts",
        // Python
        "poetry.lock", "Pipfile.lock", "pdm.lock", "uv.lock", "pixi.lock", "pylock.toml",
        // Ruby, PHP, Elixir, Erlang, Dart, Crystal
        "Gemfile.lock", "gems.locked", "composer.lock", "mix.lock", "rebar.lock", "pubspec.lock",
        "shard.lock",
        // Rust, Go, Swift, Apple
        "Cargo.lock", "go.sum", "go.work.sum", "Package.resolved", "Podfile.lock",
        "Cartfile.resolved",
        // JVM, .NET
        "gradle.lockfile", "packages.lock.json", "paket.lock",
        // Haskell, Julia, R, C/C++, Nix, Bazel, Terraform
        "stack.yaml.lock", "cabal.project.freeze", "Manifest.toml", "renv.lock", "conan.lock",
        "flake.lock", "MODULE.bazel.lock", ".terraform.lock.hcl",
    ]

    /// Endings code generators stamp on what they write: minified bundles, source maps,
    /// protobuf/gRPC stubs, and the build-runner outputs of Dart and C#.
    private static let generatedSuffixes: [String] = [
        ".lockfile",
        ".min.js", ".min.mjs", ".min.cjs", ".min.css", ".js.map", ".mjs.map", ".cjs.map",
        ".css.map", ".d.ts.map", ".tsbuildinfo",
        ".pb.go", ".pb.gw.go", ".pb.cc", ".pb.h", ".pb.swift", ".grpc.swift", "_pb2.py",
        "_pb2.pyi", "_pb2_grpc.py", "_pb.js", "_pb.d.ts", "_grpc_pb.js", "_grpc_pb.d.ts",
        ".pb.dart", ".pbenum.dart", ".pbjson.dart", ".pbgrpc.dart", ".pbserver.dart",
        ".g.dart", ".freezed.dart", ".gr.dart", ".mocks.dart", ".chopper.dart",
        ".g.cs", ".g.i.cs", ".designer.cs", ".xcworkspacedata", ".xcuserstate",
    ]

    /// `generatedSuffixes` by the extension each ends in, so a file is only tested against
    /// the endings it could have.
    private static let generatedSuffixesByExtension = Dictionary(grouping: generatedSuffixes) {
        String($0.split(separator: ".").last ?? "")
    }

    static func isGeneratedFile(_ name: String) -> Bool {
        if generatedNames.contains(name) { return true }
        let lowered = name.lowercased()
        let fileExtension = lowered.lastIndex(of: ".").map { String(lowered[lowered.index(after: $0)...]) } ?? ""
        if generatedSuffixesByExtension[fileExtension]?.contains(where: lowered.hasSuffix) == true { return true }
        // Every rule below names "gen".
        guard containsIgnoringCase(lowered, "gen") else { return false }
        let parts = lowered.split(separator: ".").map(String.init)
        // `routeTree.gen.ts`, `schema.generated.graphql`: a marker between the stem and
        // the extension.
        if parts.count >= 3, parts.dropFirst().dropLast().contains(where: { $0 == "gen" || $0 == "generated" }) {
            return true
        }
        let stem = parts.first ?? lowered
        // Kubernetes' `zz_generated.deepcopy.go`, and `_generated`/`-gen` stems.
        return stem.hasPrefix("zz_generated")
            || stem.hasSuffix("_generated") || stem.hasSuffix("-generated")
            || stem.hasSuffix("_gen") || stem.hasSuffix("-gen")
    }

    /// The comment a generator writes at the top of its output: Go's `// Code generated
    /// … DO NOT EDIT.`, protoc's and Thrift's, Facebook's `@generated`, .NET's
    /// `<auto-generated>`. Only the head of a file is read — these sit above any code,
    /// and a marker quoted halfway down a source file is about something else.
    static func hasGeneratedHeader(_ head: Data) -> Bool {
        guard !head.prefix(1024).contains(0),
              let text = String(data: head.prefix(1024), encoding: .utf8)
                ?? String(data: head.prefix(1023), encoding: .utf8)
        else { return false }
        if generatedHeaderMarkers.contains(where: text.contains) { return true }
        let lowered = text.lowercased()
        return generatedHeaderPhrases.contains(where: lowered.contains)
    }

    // Spelled in pieces so this file's own head never reads as generated.
    private static let generatedHeaderMarkers = ["@" + "generated", "DO NOT " + "EDIT", "<auto-" + "generated"]
    private static let generatedHeaderPhrases = [
        "autogenerated " + "by", "auto-generated " + "by", "automatically generated " + "by",
        "generated by the protocol buffer " + "compiler",
    ]

    // MARK: Tests

    /// Folders that hold tests across ecosystems: `tests/` and `spec/` everywhere,
    /// Jest's `__tests__`/`__mocks__`/`__snapshots__`, Go's `testdata`, Gradle's
    /// `src/test` and `src/androidTest`.
    private static let testFolders: Set<String> = [
        "test", "tests", "__tests__", "spec", "specs", "__specs__", "testdata", "test-data",
        "test_data", "testfixtures", "__mocks__", "__snapshots__", "__fixtures__", "e2e",
        "cypress", "androidtest", "integrationtest", "uitests",
    ]

    static func isTestFolder(_ name: String) -> Bool {
        testFolders.contains(name.lowercased())
            // Xcode and SwiftPM targets: `FyoloTests`, and `AppUITests`, whose acronym
            // the CamelCase rule would otherwise read as part of the word.
            || hasCamelCaseSuffix(name, ["Tests", "Test", "Specs", "Spec"]) || name.hasSuffix("UITests")
    }

    /// Test runners' own configuration: part of the test suite, not of the program.
    private static let testConfigPrefixes = [
        "jest.config.", "jest.setup.", "vitest.config.", "vitest.workspace.", "vitest.setup.",
        "playwright.config.", "cypress.config.", "karma.conf.", ".mocharc",
    ]
    private static let testConfigNames: Set<String> = [
        "conftest.py", "pytest.ini", "phpunit.xml", "phpunit.xml.dist", ".rspec",
    ]

    private static let jvmExtensions: Set<String> = ["java", "kt", "kts", "groovy", "scala"]

    static func isTestFile(_ name: String) -> Bool {
        if testConfigNames.contains(name) { return true }
        let lowered = name.lowercased()
        if testConfigPrefixes.contains(where: lowered.hasPrefix) { return true }
        // Jest snapshots, and Perl's `.t` test scripts.
        if lowered.hasSuffix(".snap") || lowered.hasSuffix(".t") { return true }

        let parts = name.split(separator: ".", omittingEmptySubsequences: false).map(String.init)
        // `button.test.tsx`, `user.spec.ts`, `login.e2e.ts`, `form.cy.ts`.
        if parts.count >= 3, parts.dropFirst().dropLast()
            .contains(where: { ["test", "tests", "spec", "specs", "e2e", "cy"].contains($0.lowercased()) }) {
            return true
        }
        let stem = parts.count > 1 ? parts.dropLast().joined(separator: ".") : name
        let loweredStem = stem.lowercased()
        // `test_parser.py`, `test-utils.R`, and a module that is nothing but tests.
        if ["test", "tests"].contains(loweredStem)
            || loweredStem.hasPrefix("test_") || loweredStem.hasPrefix("test-") {
            return true
        }
        // Go's `_test.go`, Python's `_test.py`, Ruby's `_spec.rb`, Erlang's `_SUITE.erl`,
        // C++'s `_unittest.cc`.
        if ["_test", "_tests", "_spec", "_suite", "_unittest", "-test", "-spec"]
            .contains(where: loweredStem.hasSuffix) {
            return true
        }
        // `ParserTests.swift`, `UserServiceTest.java`, `RouterSpec.hs`, `setupTests.js`.
        if hasCamelCaseSuffix(stem, ["Tests", "Test", "Specs", "Spec"]) || stem.hasSuffix("UITests") { return true }
        // Maven Failsafe's integration tests: `CheckoutIT.java`.
        let fileExtension = parts.count > 1 ? (parts.last ?? "").lowercased() : ""
        return jvmExtensions.contains(fileExtension) && hasCamelCaseSuffix(stem, ["IT"])
    }

    /// Whether `word` ends in one of `suffixes` as a CamelCase word of its own: `UserTest`
    /// and `parserTests` do, `Latest` and `Contest` do not (lowercase `t`), and neither
    /// does `ABTest`, where the capital before it makes it part of an acronym.
    private static func hasCamelCaseSuffix(_ word: String, _ suffixes: [String]) -> Bool {
        for suffix in suffixes where word.hasSuffix(suffix) && word.count > suffix.count {
            let before = word[word.index(word.endIndex, offsetBy: -suffix.count - 1)]
            if before.isLowercase || before.isNumber { return true }
        }
        return false
    }
}

/// Everything the file tree knows about its rows beyond the listing: how each file differs
/// from the branch's base, which ones are generated, and which ones a terminal has
/// reported errors in.
///
/// One per tree, owned by its `DeviceFileTreeModel` and so kept with it in the cache:
/// coming back to a checkout finds the colors already worked out.
///
/// **Git, the same way the Changes pane reads it.** The branch is measured against the
/// base the Compare tab would pick — `origin/HEAD`, else the conventional trunk — so a
/// file an agent already committed stays marked until the branch merges. The status and
/// the comparison come from a `GitPanelModel`: on this Mac it runs `git` and watches the
/// folder; on another machine it subscribes to that device's `git:` resource. Nothing
/// here polls.
///
/// What needs a local disk — whitespace-only changes, `.gitattributes`, a generated
/// file's header — is worked out on this Mac only. A tree on another machine still gets
/// its added/modified colors and everything decided by name.
@MainActor
final class FileTreeDecorations: ObservableObject {
    /// Bumped whenever any row's decoration may have changed.
    @Published private(set) var revision = 0
    /// How many files the working tree has changed — the inspector's Changes badge, read
    /// off the status this already keeps rather than a second `git status` of its own.
    private(set) var workingChangeCount = 0
    var onWorkingChangeCount: ((Int) -> Void)?

    let root: String
    private let checkout: Checkout
    private weak var tree: DeviceFileTreeModel?

    private var git: GitPanelModel?
    private var subscriptions: Set<AnyCancellable> = []
    private var isActive = false
    private var isShowing: () -> Bool = { false }

    /// Keyed by the row's path, as the tree holds it.
    private var changes: [String: FileDecoration.Change] = [:]
    /// What `.gitattributes` or a file's own header said, overriding the name rules —
    /// including `false`, for a lockfile a repository says to review.
    private var generatedOverrides: [String: Bool] = [:]
    private var inspectedPaths: Set<String> = []
    /// Folders holding nothing but generated files, at any depth.
    private var generatedFolders: Set<String> = []
    /// Every file under the root, as git lists it, with what `.gitattributes` says about
    /// each — the whole tree, including folders never opened, so a collapsed folder of
    /// generated code is marked before anyone looks inside. `nil` on another device, or
    /// outside a repository, where the folders the tree has listed are all there is.
    private var listing: (files: [String], attributes: [String: Bool])?
    /// What the listing was read at: `HEAD`, and the paths the working tree added,
    /// removed or renamed. Editing a file changes neither, so it never re-reads.
    private var listingKey: String?
    private var folderRollupScheduled = false
    private var folderRollupGeneration = 0
    private var errorFiles: Set<String> = []
    private var errorFolders: Set<String> = []
    private var kinds: [String: FileDecoration.Kind?] = [:]

    /// `root` relative to the repository's top (`web/`), so status paths can be mapped
    /// to rows. Empty on another device, whose checkouts are their repository's top.
    private var repositoryPrefix: String?
    private var recomputeGeneration = 0
    private var recomputeScheduled = false

    init(checkout: Checkout, root: String, tree: DeviceFileTreeModel) {
        self.checkout = checkout
        self.root = root
        self.tree = tree
        TerminalDiagnostics.shared.$revision
            .sink { [weak self] _ in
                // Published before the new value lands; read it a turn later.
                Task { @MainActor in self?.updateErrors() }
            }
            .store(in: &subscriptions)
    }

    private var isOnThisMac: Bool { !checkout.isOnAnotherDevice }

    /// Starts reading, or resumes it. `isShowing` says whether the tree is worth keeping
    /// current right now; a refresh arriving while it is not is held and replayed here.
    func start(isShowing: @escaping () -> Bool) {
        self.isShowing = isShowing
        isActive = true
        let git = git ?? makeGit()
        git.flushDeferredRefresh()
        Task {
            await git.load()
            if git.compareContext == nil { await git.loadCompareContext() }
        }
        TerminalDiagnostics.shared.revalidate(onDevice: checkout.deviceIdentity, isLocal: isOnThisMac)
        updateErrors()
        treeDidChange()
    }

    /// Stands down while the tree is off screen: a device's status subscription is
    /// dropped, and this Mac's folder watch parks its refreshes until `start`.
    func stop() {
        isActive = false
        git?.stopDeviceWatch()
    }

    /// Replays a refresh that was parked while the tree was covered.
    func resume() {
        guard isActive else { return }
        git?.flushDeferredRefresh()
    }

    func decoration(for node: DeviceFileNode) -> FileDecoration {
        // A folder of tests is not itself a test: only files carry the background. A
        // folder is generated only when everything in it is.
        FileDecoration(
            kind: node.isDirectory ? (generatedFolders.contains(node.path) ? .generated : nil) : kind(for: node),
            change: node.isDirectory ? nil : changes[node.path],
            isIgnored: node.isIgnored,
            hasError: node.isDirectory ? errorFolders.contains(node.path) : errorFiles.contains(node.path))
    }

    private func kind(for node: DeviceFileNode) -> FileDecoration.Kind? {
        if let override = generatedOverrides[node.path] {
            if override { return .generated }
            let byName = cachedKind(for: node)
            return byName == .generated ? nil : byName
        }
        return cachedKind(for: node)
    }

    private func cachedKind(for node: DeviceFileNode) -> FileDecoration.Kind? {
        if let cached = kinds[node.path] { return cached }
        let kind = relativePath(of: node.path).flatMap {
            FileClassifier.kind(of: $0, isDirectory: node.isDirectory)
        }
        kinds[node.path] = kind
        return kind
    }

    private func relativePath(of path: String) -> String? {
        let base = root.hasSuffix("/") ? root : root + "/"
        guard path.hasPrefix(base) else { return nil }
        return String(path.dropFirst(base.count))
    }

    private func bump() { revision &+= 1 }

    // MARK: Git

    private func makeGit() -> GitPanelModel {
        let model = GitPanelModel(
            repoRoot: root,
            device: isOnThisMac ? nil : checkout.device.route,
            isPaneVisible: { [weak self] in
                guard let self else { return false }
                return self.isActive && self.isShowing()
            })
        // A new branch, or a base that appeared with a fetch: measure against the
        // base the Compare tab would offer.
        model.$compareContext
            .sink { [weak model] context in
                guard let model, let context else { return }
                Task { await model.setCompareBase(context.suggestedBase) }
            }
            .store(in: &subscriptions)
        model.$changes.map { _ in () }
            .merge(with: model.$compare.map { _ in () })
            .sink { [weak self] in self?.scheduleRecompute() }
            .store(in: &subscriptions)
        git = model
        return model
    }

    /// Coalesces the status and the comparison landing in the same turn into one pass.
    private func scheduleRecompute() {
        guard !recomputeScheduled else { return }
        recomputeScheduled = true
        Task { @MainActor in
            recomputeScheduled = false
            await recomputeChanges()
        }
    }

    private func recomputeChanges() async {
        guard let git else { return }
        recomputeGeneration += 1
        let generation = recomputeGeneration
        let working = git.changes
        let branch = git.compare?.files ?? []
        var merged = Self.merge(working: working, branch: branch)

        if repositoryPrefix == nil {
            repositoryPrefix = isOnThisMac ? (await GitService.pathPrefix(in: root) ?? "") : ""
        }
        if isOnThisMac {
            let modified = merged.filter { $0.value == .modified }.map(\.key)
            let cosmetic = await GitService.cosmeticChanges(modified, against: git.compare?.base, in: root)
            for path in cosmetic { merged[path] = .cosmetic }
        }
        guard generation == recomputeGeneration else { return }

        let prefix = repositoryPrefix ?? ""
        let base = root.hasSuffix("/") ? root : root + "/"
        var mapped: [String: FileDecoration.Change] = [:]
        for (path, change) in merged where path.hasPrefix(prefix) {
            mapped[base + path.dropFirst(prefix.count)] = change
        }
        workingChangeCount = working.count
        onWorkingChangeCount?(working.count)
        if mapped != changes {
            changes = mapped
            bump()
        }
        if isOnThisMac { await refreshListing(working: working) }
    }

    /// The branch's changes against its base, from the two halves git reports apart:
    /// `branch` — the committed diff from the merge base — and `working`, what is not
    /// committed yet. Keyed by path from the repository's top. A file that was not at
    /// the base is `added` however many times it has been edited since; one deleted
    /// along the way has no row to mark.
    nonisolated static func merge(working: [GitChange], branch: [GitChange]) -> [String: FileDecoration.Change] {
        var result: [String: FileDecoration.Change] = [:]
        var deletedOnBranch: Set<String> = []
        for change in branch {
            switch change.status {
            case .added, .untracked: result[change.path] = .added
            case .deleted: deletedOnBranch.insert(change.path)
            case .modified, .renamed, .copied, .conflicted: result[change.path] = .modified
            }
        }
        for change in working {
            switch change.status {
            case .deleted:
                result[change.path] = nil
            case .added, .untracked:
                // Deleted in a commit and written again is a file the base had.
                result[change.path] = deletedOnBranch.contains(change.path) ? .modified
                    : (result[change.path] ?? .added)
            case .modified, .renamed, .copied, .conflicted:
                if result[change.path] != .added { result[change.path] = .modified }
            }
        }
        return result
    }

    // MARK: Generated, from the repository and the files themselves

    /// Called whenever the tree's realized rows change. On this Mac, reads what the
    /// name rules cannot know for the files that just appeared: the repository's
    /// `linguist-generated` attribute, and a generator's header.
    func treeDidChange() {
        guard isActive, let tree else { return }
        // Without a listing the folders are judged from the rows, which just moved.
        if listing == nil { scheduleFolderRollup() }
        guard isOnThisMac else { return }
        let fresh = tree.realizedNodes()
            .filter { !$0.isDirectory && !$0.isIgnored && $0.notice == nil && !inspectedPaths.contains($0.path) }
            .map(\.path)
        guard !fresh.isEmpty else { return }
        inspectedPaths.formUnion(fresh)
        let root = root
        let relative = fresh.compactMap { path in relativePath(of: path).map { (path, $0) } }
        Task {
            let attributes = await GitService.linguistGenerated(relative.map(\.1), in: root)
            let headers = await Task.detached(priority: .utility) {
                relative.map(\.0).filter { path in
                    guard let handle = FileHandle(forReadingAtPath: path) else { return false }
                    defer { try? handle.close() }
                    do {
                        return FileClassifier.hasGeneratedHeader(try handle.read(upToCount: 1024) ?? Data())
                    } catch {
                        return false
                    }
                }
            }.value
            var changed = false
            for (path, relativePath) in relative {
                let verdict = attributes[relativePath] ?? (headers.contains(path) ? true : nil)
                guard let verdict, generatedOverrides[path] != verdict else { continue }
                generatedOverrides[path] = verdict
                changed = true
            }
            if changed {
                bump()
                scheduleFolderRollup()
            }
        }
    }

    /// A checkout past this many files keeps folder colors to the folders it has listed:
    /// the whole-tree pass is linear, but its memory is not free.
    private static let listingLimit = 250_000

    /// Re-reads the checkout's file list when its shape may have moved: a new `HEAD`, or
    /// paths added, removed or renamed. A run of edits to existing files — nearly every
    /// status pass — costs one `rev-parse` and stops there.
    private func refreshListing(working: [GitChange]) async {
        let structure = working
            .filter { $0.status != .modified || ($0.path as NSString).lastPathComponent == ".gitattributes" }
            .map { $0.status.letter + $0.path }
            .sorted()
            .joined(separator: "\0")
        let key = (await GitService.head(in: root) ?? "") + "\0" + structure
        guard key != listingKey else { return }
        listingKey = key
        guard let files = await GitService.listedFiles(in: root), files.count <= Self.listingLimit else {
            guard listingKey == key else { return }
            listing = nil
            scheduleFolderRollup()
            return
        }
        // One `check-attr` for the whole list, so a repository's `linguist-generated`
        // rules — nested `.gitattributes`, `info/attributes`, macros — are git's to apply.
        let attributes = await GitService.linguistGenerated(files, in: root)
        guard listingKey == key else { return }
        listing = (files, attributes)
        scheduleFolderRollup()
    }

    private func scheduleFolderRollup() {
        guard !folderRollupScheduled else { return }
        folderRollupScheduled = true
        Task { @MainActor in
            folderRollupScheduled = false
            await recomputeFolderRollup()
        }
    }

    private func recomputeFolderRollup() async {
        folderRollupGeneration += 1
        let generation = folderRollupGeneration
        let folders: Set<String>
        if let listing {
            // What the rows learned from a file's own header joins what git said.
            let headers = Dictionary(uniqueKeysWithValues: generatedOverrides.compactMap { path, verdict in
                relativePath(of: path).map { ($0, verdict) }
            })
            let base = root.hasSuffix("/") ? root : root + "/"
            folders = await Task.detached(priority: .utility) {
                let relative = Self.generatedFolders(files: listing.files) { path in
                    headers[path] ?? listing.attributes[path] ?? FileClassifier.isGenerated(path)
                }
                return Set(relative.map { base + $0 })
            }.value
        } else {
            folders = listedGeneratedFolders()
        }
        guard generation == folderRollupGeneration, folders != generatedFolders else { return }
        generatedFolders = folders
        bump()
    }

    /// The folders, relative like `files`, that hold at least one generated file and
    /// nothing else. One pass: each file marks its folders upward, and stops at the
    /// first that an earlier file of the same verdict already marked, since everything
    /// above that is marked too.
    nonisolated static func generatedFolders(files: [String], isGenerated: (String) -> Bool) -> Set<String> {
        var holdsGenerated: Set<Substring> = []
        var holdsOther: Set<Substring> = []
        for file in files {
            let generated = isGenerated(file)
            var end = file.lastIndex(of: "/")
            while let slash = end {
                let folder = file[..<slash]
                if generated {
                    guard holdsGenerated.insert(folder).inserted else { break }
                } else {
                    guard holdsOther.insert(folder).inserted else { break }
                }
                end = folder.lastIndex(of: "/")
            }
        }
        return Set(holdsGenerated.subtracting(holdsOther).map(String.init))
    }

    /// The same judgment from the rows the tree has listed, for a checkout git cannot be
    /// asked about from here. A folder not yet listed — or listed only in part — is not
    /// known to be all generated, so it is not marked. Ignored entries count for
    /// nothing either way, as they do in git's list.
    private func listedGeneratedFolders() -> Set<String> {
        guard let tree else { return [] }
        enum Verdict { case generated, other, neutral }
        var verdicts: [String: Verdict] = [:]
        func verdict(_ node: DeviceFileNode) -> Verdict {
            if node.notice != nil { return .other }
            if node.isIgnored { return .neutral }
            guard node.isDirectory else { return kind(for: node) == .generated ? .generated : .other }
            if let known = verdicts[node.path] { return known }
            var result = Verdict.other
            if let children = node.listedChildren {
                result = .neutral
                for child in children {
                    switch verdict(child) {
                    case .generated: result = .generated
                    case .other: result = .other
                    case .neutral: continue
                    }
                    if result == .other { break }
                }
            }
            verdicts[node.path] = result
            return result
        }
        return Set(tree.realizedNodes().filter { $0.isDirectory && verdict($0) == .generated }.map(\.path))
    }

    // MARK: Errors

    /// The tree's device reported that these directories' contents moved. A file an
    /// error was reported against has probably just been edited, which makes the
    /// report stale.
    func directoriesChanged(_ directories: [String]) {
        TerminalDiagnostics.shared.directoriesChanged(
            directories, onDevice: checkout.deviceIdentity, isLocal: isOnThisMac)
    }

    func updateErrors() {
        let files = TerminalDiagnostics.shared.errorFiles(onDevice: checkout.deviceIdentity, under: root)
        guard files != errorFiles else { return }
        var folders: Set<String> = []
        let base = root.hasSuffix("/") ? String(root.dropLast()) : root
        for file in files {
            var folder = (file as NSString).deletingLastPathComponent
            while folder.count > base.count, folders.insert(folder).inserted {
                folder = (folder as NSString).deletingLastPathComponent
            }
        }
        errorFiles = files
        errorFolders = folders
        bump()
    }
